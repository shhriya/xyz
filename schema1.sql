```sql
-- ============================================================
-- Healthcare Claims Analytics Source Schema
-- Snowflake DDL shared by Client Data Architecture Team
-- ============================================================

CREATE TABLE RAW_PATIENTS (
    PATIENT_ID VARCHAR,
    FIRST_NAME VARCHAR,
    LAST_NAME VARCHAR,
    DATE_OF_BIRTH DATE,
    GENDER VARCHAR,
    EMAIL VARCHAR,
    PHONE VARCHAR,
    ADDRESS VARCHAR,
    CITY VARCHAR,
    STATE VARCHAR,
    PINCODE VARCHAR,
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP
);

CREATE TABLE RAW_POLICIES (
    POLICY_ID VARCHAR,
    PATIENT_ID VARCHAR,
    POLICY_NUMBER VARCHAR,
    POLICY_TYPE VARCHAR,
    COVERAGE_AMOUNT NUMBER(12,2),
    PREMIUM_AMOUNT NUMBER(12,2),
    POLICY_STATUS VARCHAR,
    EFFECTIVE_DATE DATE,
    EXPIRY_DATE DATE,
    RENEWAL_DATE DATE,
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP
);

CREATE TABLE RAW_HOSPITALS (
    HOSPITAL_ID VARCHAR,
    HOSPITAL_NAME VARCHAR,
    HOSPITAL_TYPE VARCHAR,
    CITY VARCHAR,
    STATE VARCHAR,
    IS_NETWORK_PARTNER BOOLEAN,
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP
);

CREATE TABLE RAW_PROVIDERS (
    PROVIDER_ID VARCHAR,
    HOSPITAL_ID VARCHAR,
    PROVIDER_NAME VARCHAR,
    SPECIALIZATION VARCHAR,
    PROVIDER_STATUS VARCHAR,
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP
);

CREATE TABLE RAW_DIAGNOSES (
    DIAGNOSIS_ID VARCHAR,
    ICD10_CODE VARCHAR,
    DIAGNOSIS_NAME VARCHAR,
    DISEASE_CATEGORY VARCHAR,
    CREATED_AT TIMESTAMP
);

CREATE TABLE RAW_CLAIMS (
    CLAIM_ID VARCHAR,
    PATIENT_ID VARCHAR,
    POLICY_ID VARCHAR,
    HOSPITAL_ID VARCHAR,
    PROVIDER_ID VARCHAR,
    DIAGNOSIS_ID VARCHAR,
    CLAIM_SUBMITTED_DATE TIMESTAMP,
    CLAIM_APPROVED_DATE TIMESTAMP,
    CLAIM_STATUS VARCHAR,
    CLAIM_AMOUNT NUMBER(12,2),
    DEDUCTIBLE_AMOUNT NUMBER(12,2),
    APPROVED_AMOUNT NUMBER(12,2),
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP
);

CREATE TABLE RAW_CLAIM_PAYMENTS (
    PAYMENT_ID VARCHAR,
    CLAIM_ID VARCHAR,
    PAYMENT_DATE TIMESTAMP,
    PAYMENT_STATUS VARCHAR,
    PAYMENT_AMOUNT NUMBER(12,2),
    PAYMENT_REFERENCE VARCHAR,
    CREATED_AT TIMESTAMP
);
```
