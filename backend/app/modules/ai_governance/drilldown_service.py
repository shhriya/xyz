def fetch_jobs(conn, fq: str, source_id: str, period: str) -> List[Dict[str, Any]]:
    """Every job, with its run counts and timings over the period.

    Built from GOV_RUNS rather than GOV_JOBS because GOV_JOBS has no status or duration of its own —
    a job's health only exists as an aggregate of its runs. The join back to GOV_JOBS is for the
    descriptive attributes (schedule, environment, active flag) and is an outer join so a job that
    ran but has since been deleted in dbt Cloud still appears.
    """
    runs_since = since_clause("STARTED_AT", period)
    result = query_rows(
        conn,
        f"""
        WITH runs AS (
            SELECT JOB_ID, JOB_NAME, STATUS, STARTED_AT, DURATION_SECS
            FROM {fq}.GOV_RUNS
            WHERE SOURCE_ID = %s {runs_since}
        ),
        agg AS (
            SELECT
                JOB_ID,
                MAX(JOB_NAME)                                               AS JOB_NAME,
                COUNT(*)                                                    AS RUN_COUNT,
                COUNT_IF({SUCCESS_SQL})                                     AS SUCCESS_COUNT,
                COUNT_IF({FAILURE_SQL})                                     AS FAILURE_COUNT,
                ROUND(AVG(DURATION_SECS), 2)                                AS AVG_DURATION_SECS,
                ROUND(SUM(DURATION_SECS), 2)                                AS TOTAL_DURATION_SECS,
                ROUND(MAX(DURATION_SECS), 2)                                AS MAX_DURATION_SECS,
                MAX(STARTED_AT)                                             AS LAST_RUN_AT
            FROM runs
            GROUP BY JOB_ID
        ),
        last_status AS (
            SELECT JOB_ID, STATUS AS LAST_STATUS
            FROM runs
            QUALIFY ROW_NUMBER() OVER (PARTITION BY JOB_ID ORDER BY STARTED_AT DESC NULLS LAST) = 1
        )
        SELECT
            a.JOB_ID,
            COALESCE(a.JOB_NAME, j.JOB_NAME, 'Job ' || a.JOB_ID)            AS JOB_NAME,
            a.RUN_COUNT, a.SUCCESS_COUNT, a.FAILURE_COUNT,
            a.AVG_DURATION_SECS, a.TOTAL_DURATION_SECS, a.MAX_DURATION_SECS,
            a.LAST_RUN_AT, l.LAST_STATUS,
            ROUND(100 * a.SUCCESS_COUNT / NULLIF(a.RUN_COUNT, 0), 1)        AS SUCCESS_RATE_PCT,
            j.ATTRIBUTES:environment_name::VARCHAR                          AS ENVIRONMENT,
            j.ATTRIBUTES:schedule_humanized::VARCHAR                        AS SCHEDULE,
            COALESCE(j.ATTRIBUTES:is_active::BOOLEAN, TRUE)                 AS IS_ACTIVE
        FROM agg a
        LEFT JOIN last_status l ON l.JOB_ID = a.JOB_ID
        LEFT JOIN {fq}.GOV_JOBS j ON j.SOURCE_ID = %s AND j.JOB_ID = a.JOB_ID
        ORDER BY a.LAST_RUN_AT DESC NULLS LAST
        LIMIT 500
        """,
        (source_id, source_id),
    )
    return result["rows"]


