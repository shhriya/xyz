def fetch_summary(conn, fq: str, source_id: str, period: str) -> Dict[str, Any]:
    """Headline counters for the strip above the tabs.

    Total jobs is deliberately *not* filtered by period — it answers "how many jobs exist", which
    does not change because you narrowed the date range. Everything run-shaped is filtered.
    """
    since = since_clause("STARTED_AT", period)
    runs = query_rows(
        conn,
        f"""
        SELECT
            COUNT(*)                                        AS TOTAL_RUNS,
            COUNT_IF({SUCCESS_SQL})                         AS SUCCESSFUL_RUNS,
            COUNT_IF({FAILURE_SQL})                         AS FAILED_RUNS,
            COUNT(DISTINCT JOB_ID)                          AS JOBS_WITH_RUNS,
            ROUND(AVG(DURATION_SECS), 1)                    AS AVG_RUN_SECS,
            ROUND(SUM(DURATION_SECS), 1)                    AS TOTAL_RUN_SECS,
            MAX(STARTED_AT)                                 AS LAST_RUN_AT
        FROM {fq}.GOV_RUNS
        WHERE SOURCE_ID = %s {since}
        """,
        (source_id,),
    )["rows"]
    runs_row = runs[0] if runs else {}

    total_jobs = 0
    try:
        jobs = query_rows(
            conn, f"SELECT COUNT(*) AS TOTAL_JOBS FROM {fq}.GOV_JOBS WHERE SOURCE_ID = %s", (source_id,)
        )["rows"]
        total_jobs = int((jobs[0] if jobs else {}).get("TOTAL_JOBS") or 0)
    except Exception:
        pass

    models_run = 0
    try:
        mr = query_rows(
            conn,
            f"SELECT COUNT(DISTINCT NAME) AS MODELS_RUN FROM {fq}.GOV_RUN_RESULTS "
            f"WHERE SOURCE_ID = %s {since}",
            (source_id,),
        )["rows"]
        models_run = int((mr[0] if mr else {}).get("MODELS_RUN") or 0)
    except Exception:
        pass

    total_runs = int(runs_row.get("TOTAL_RUNS") or 0)
    successful = int(runs_row.get("SUCCESSFUL_RUNS") or 0)
    return {
        **describe_period(period),
        "totalJobs": total_jobs,
        "jobsWithRuns": int(runs_row.get("JOBS_WITH_RUNS") or 0),
        "totalRuns": total_runs,
        "successfulRuns": successful,
        "failedRuns": int(runs_row.get("FAILED_RUNS") or 0),
        "successRatePct": round(100.0 * successful / total_runs, 1) if total_runs else None,
        "avgRunSecs": runs_row.get("AVG_RUN_SECS"),
        "totalRunSecs": runs_row.get("TOTAL_RUN_SECS"),
        "lastRunAt": runs_row.get("LAST_RUN_AT"),
        "modelsRun": models_run,
    }


def data_coverage(conn, fq: str, source_id: str) -> Dict[str, Any]:
    """How much history actually exists, so the UI can be honest when a window looks empty.

    Without this a user picking "Last 30 days" on a source synced yesterday sees near-zero numbers
    and reasonably concludes the feature is broken, rather than that the history only starts here.
    """
    try:
        rows = query_rows(
            conn,
            f"""
            SELECT
                MIN(STARTED_AT) AS EARLIEST_RUN_AT,
                MAX(STARTED_AT) AS LATEST_RUN_AT,
                COUNT(*)        AS RUN_ROWS
            FROM {fq}.GOV_RUNS
            WHERE SOURCE_ID = %s
            """,
            (source_id,),
        )["rows"]
        row = rows[0] if rows else {}
        # Separate try: GOV_RUN_QUERIES only exists after a sync that followed query capture being
        # added, and run coverage is still worth reporting without it.
        qrow: Dict[str, Any] = {}
        try:
            queries = query_rows(
                conn,
                f"SELECT COUNT(*) AS QUERY_ROWS, COUNT_IF(QUERY_TEXT IS NOT NULL) AS ENRICHED_ROWS "
                f"FROM {fq}.GOV_RUN_QUERIES WHERE SOURCE_ID = %s",
                (source_id,),
            )["rows"]
            qrow = queries[0] if queries else {}
        except Exception:
            qrow = {}
        return {
            "earliestRunAt": row.get("EARLIEST_RUN_AT"),
            "latestRunAt": row.get("LATEST_RUN_AT"),
            "runRows": int(row.get("RUN_ROWS") or 0),
            "queryRows": int(qrow.get("QUERY_ROWS") or 0),
            "enrichedQueryRows": int(qrow.get("ENRICHED_ROWS") or 0),
        }
    except Exception as e:
        return {"error": str(e)[:200]}
