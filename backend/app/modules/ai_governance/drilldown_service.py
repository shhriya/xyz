def fetch_job_models(conn, fq: str, source_id: str, job_id: str, period: str) -> List[Dict[str, Any]]:
    """Every model the job ran over the period, aggregated per model with its latest run's outcome.

    Two of the joins are optional and are dropped if their table isn't there:
      - DBT_MODELS only exists for dbt sources (layer, materialization, schema).
      - GOV_RUN_QUERIES only exists once a sync has run since query capture was added.

    Both are enrichment, not the answer. Joining them unconditionally meant a missing table failed
    the whole statement and the user saw "No models recorded for this job" — the models were there
    the whole time. So the query degrades one join at a time instead of all-or-nothing.
    """
    rows: List[Dict[str, Any]] = []
    for with_models, with_queries in ((True, True), (True, False), (False, False)):
        try:
            rows = _job_models_query(conn, fq, source_id, job_id, period, with_models, with_queries)
            if rows:
                return rows
            break
        except Exception as e:
            if not with_models and not with_queries:
                print(f"[drilldown] core model query failed: {e}")
            else:
                print(f"[drilldown] model query degraded (models={with_models}, queries={with_queries}): {e}")

    # Fallback 1: if no models recorded in the filtered period, check all time for this job
    if not rows and period != "all":
        try:
            rows = _job_models_query(conn, fq, source_id, job_id, "all", True, False)
            if rows:
                return rows
        except Exception:
            pass

    # Fallback 2: if run_results have no entries yet, surface models from the project manifest (DBT_MODELS)
    if not rows:
        try:
            manifest_res = query_rows(
                conn,
                f"""
                SELECT
                    m.MODEL_NAME,
                    'model'                                 AS RESOURCE_TYPE,
                    0                                       AS RUN_COUNT,
                    0                                       AS SUCCESS_COUNT,
                    0                                       AS FAILURE_COUNT,
                    0.0                                     AS AVG_DURATION_SECS,
                    0.0                                     AS MAX_DURATION_SECS,
                    0.0                                     AS TOTAL_DURATION_SECS,
                    0                                       AS AVG_ROWS_AFFECTED,
                    NULL                                    AS LAST_RUN_AT,
                    'registered'                            AS LAST_STATUS,
                    0.0                                     AS LAST_DURATION_SECS,
                    0                                       AS LAST_ROWS_AFFECTED,
                    NULL                                    AS LAST_RUN_ID,
                    NULL                                    AS LAST_RESULT_ID,
                    m.MODEL_LAYER,
                    m.MATERIALIZATION,
                    m.SCHEMA_NAME,
                    m.DATABASE_NAME,
                    1                                       AS QUERY_COUNT
                FROM {fq}.DBT_MODELS m
                WHERE m.SOURCE_ID = %s
                ORDER BY m.MODEL_LAYER, m.MODEL_NAME
                LIMIT 500
                """,
                (source_id,),
            )
            rows = manifest_res.get("rows", [])
        except Exception as e:
            print(f"[drilldown] manifest models fallback failed: {e}")

    return rows


def _job_models_query(
    conn, fq: str, source_id: str, job_id: str, period: str, with_models: bool, with_queries: bool,
) -> List[Dict[str, Any]]:
    since = since_clause("COALESCE(r.STARTED_AT, r.FINISHED_AT, CURRENT_TIMESTAMP())", period)
    # results CTE contains 4 placeholders:
    # 1. r.SOURCE_ID = %s
    # 2. r.JOB_ID = %s
    # 3. WHERE SOURCE_ID = %s (in GOV_RUNS fallback subquery)
    # 4. AND JOB_ID = %s      (in GOV_RUNS fallback subquery)
    params: List[Any] = [source_id, str(job_id), source_id, str(job_id)]

    if with_models:
        model_cols = "m.MODEL_LAYER, m.MATERIALIZATION, m.SCHEMA_NAME, m.DATABASE_NAME,"
        model_join = f"LEFT JOIN {fq}.DBT_MODELS m ON m.SOURCE_ID = %s AND UPPER(m.MODEL_NAME) = UPPER(a.NAME)"
        params.append(source_id)
    else:
        model_cols = ("CAST(NULL AS VARCHAR) AS MODEL_LAYER, CAST(NULL AS VARCHAR) AS MATERIALIZATION, "
                      "CAST(NULL AS VARCHAR) AS SCHEMA_NAME, CAST(NULL AS VARCHAR) AS DATABASE_NAME,")
        model_join = ""

    if with_queries:
        query_col = "COALESCE(q.QUERY_COUNT, 0) AS QUERY_COUNT"
        query_join = f"""
        LEFT JOIN (
            SELECT MODEL_NAME, COUNT(DISTINCT QUERY_ID) AS QUERY_COUNT
            FROM (
                SELECT MODEL_NAME, QUERY_ID, RUN_ID,
                       FIRST_VALUE(RUN_ID) OVER (
                           PARTITION BY MODEL_NAME ORDER BY STARTED_AT DESC NULLS LAST
                       ) AS LATEST_RUN_ID
                FROM {fq}.GOV_RUN_QUERIES
                WHERE SOURCE_ID = %s
            )
            WHERE RUN_ID = LATEST_RUN_ID
            GROUP BY MODEL_NAME
        ) q ON UPPER(q.MODEL_NAME) = UPPER(a.NAME)"""
        params.append(source_id)
    else:
        query_col = "0 AS QUERY_COUNT"
        query_join = ""

    result = query_rows(
        conn,
        f"""
        WITH results AS (
            SELECT
                r.NAME, r.RESULT_ID, r.RUN_ID, r.STATUS, r.STARTED_AT, r.DURATION_SECS,
                r.ATTRIBUTES:rows_affected::NUMBER  AS ROWS_AFFECTED,
                r.ATTRIBUTES:resource_type::VARCHAR AS RESOURCE_TYPE
            FROM {fq}.GOV_RUN_RESULTS r
            WHERE r.SOURCE_ID = %s
              AND (
                  r.JOB_ID = %s
                  OR r.RUN_ID IN (
                      SELECT RUN_ID FROM {fq}.GOV_RUNS
                      WHERE SOURCE_ID = %s AND JOB_ID = %s
                  )
              )
              {since}
        ),
        agg AS (
            SELECT
                NAME,
                MAX(RESOURCE_TYPE)                      AS RESOURCE_TYPE,
                COUNT(*)                                AS RUN_COUNT,
                COUNT_IF({SUCCESS_SQL})                 AS SUCCESS_COUNT,
                COUNT_IF({FAILURE_SQL})                 AS FAILURE_COUNT,
                ROUND(AVG(DURATION_SECS), 3)            AS AVG_DURATION_SECS,
                ROUND(MAX(DURATION_SECS), 3)            AS MAX_DURATION_SECS,
                ROUND(SUM(DURATION_SECS), 3)            AS TOTAL_DURATION_SECS,
                ROUND(AVG(ROWS_AFFECTED), 0)            AS AVG_ROWS_AFFECTED,
                MAX(STARTED_AT)                         AS LAST_RUN_AT
            FROM results
            GROUP BY NAME
        ),
        latest AS (
            SELECT NAME, RUN_ID, RESULT_ID, STATUS AS LAST_STATUS,
                   DURATION_SECS AS LAST_DURATION_SECS, ROWS_AFFECTED AS LAST_ROWS_AFFECTED
            FROM results
            QUALIFY ROW_NUMBER() OVER (PARTITION BY NAME ORDER BY STARTED_AT DESC NULLS LAST) = 1
        )
        SELECT
            a.NAME AS MODEL_NAME, a.RESOURCE_TYPE, a.RUN_COUNT, a.SUCCESS_COUNT, a.FAILURE_COUNT,
            a.AVG_DURATION_SECS, a.MAX_DURATION_SECS, a.TOTAL_DURATION_SECS, a.AVG_ROWS_AFFECTED,
            a.LAST_RUN_AT, l.LAST_STATUS, l.LAST_DURATION_SECS, l.LAST_ROWS_AFFECTED,
            l.RUN_ID AS LAST_RUN_ID, l.RESULT_ID AS LAST_RESULT_ID,
            {model_cols}
            {query_col}
        FROM agg a
        LEFT JOIN latest l ON l.NAME = a.NAME
        {model_join}
        {query_join}
        ORDER BY a.TOTAL_DURATION_SECS DESC NULLS LAST
        LIMIT 1000
        """,
        tuple(params),
    )
    return result["rows"]


