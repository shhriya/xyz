"""
Job -> model -> query drill-down, time-filtered summary KPIs, and the shared period helper.

Deliberately hand-written SQL rather than more LLM-generated V_GOV_KPI_* views. Those views bake
both the fully-qualified table name and the literal SOURCE_ID into their text at Setup and are never
regenerated by a Refresh (kpi_discovery_service.py), so they cannot take a date-range parameter and
go stale silently when anything moves. The drill-down needs to respond to a filter on every request,
so it queries the GOV_* tables directly.

Works for any source type: GOV_RUNS / GOV_RUN_RESULTS are source-agnostic, so level 2 is dbt models
for a dbt source and task instances for an Airflow one. Only level 3 is dbt-specific, because only
dbt reports a query id we can resolve back to SQL.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional

from . import source_store
from .query_capture_service import fetch_model_queries
from .snowflake_helpers import get_snowflake_conn_from_user_input, query_rows

# The periods the UI offers. "all" means no lower bound, held to roughly a year by the retention
# prune in source_registry.py.
ALLOWED_PERIODS: Dict[str, Optional[int]] = {"7": 7, "15": 15, "30": 30, "all": None}
DEFAULT_PERIOD = "30"

# Status vocabularies differ by level: GOV_RUNS carries dbt Cloud's humanized strings
# ("Success", "Error", "Cancelled"), GOV_RUN_RESULTS the raw node statuses ("success", "pass",
# "error", "skipped"). Matching on UPPER() covers both, and Airflow's lowercase states too.
SUCCESS_SQL = "UPPER(STATUS) IN ('SUCCESS', 'PASS')"
FAILURE_SQL = "UPPER(STATUS) IN ('ERROR', 'FAIL', 'FAILED', 'CANCELLED', 'CANCELED', 'UPSTREAM_FAILED')"


def open_source(source_id: str):
    """Opens a connection for a registered source. Returns (conn, fq, entry); caller closes conn."""
    entry = source_store.get_source(source_id)
    if not entry:
        raise LookupError(f"Unknown source_id '{source_id}'.")
    conn = get_snowflake_conn_from_user_input(entry["snowflake_credentials"])
    return conn, f"{entry['target_db']}.{entry['target_schema']}", entry


def resolve_period(value: Any) -> str:
    """Normalises whatever the query string carried into a key of ALLOWED_PERIODS.

    Never interpolates caller input into SQL — the returned key only ever indexes the table above,
    so an unexpected value falls back to the default instead of reaching the database.
    """
    key = str(value or "").strip().lower()
    return key if key in ALLOWED_PERIODS else DEFAULT_PERIOD


def period_days(period: str) -> Optional[int]:
    return ALLOWED_PERIODS[resolve_period(period)]


def since_clause(column: str, period: str, prefix: str = "AND") -> str:
    days = period_days(period)
    if days is None:
        return ""
    return f"{prefix} {column} >= DATEADD(day, -{int(days)}, CURRENT_TIMESTAMP())"


def describe_period(period: str) -> Dict[str, Any]:
    days = period_days(period)
    labels = {"7": "Last 7 days", "15": "Last 15 days", "30": "Last 30 days", "all": "All time"}
    return {"period": resolve_period(period), "days": days, "label": labels[resolve_period(period)]}


