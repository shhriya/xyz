def fetch_queries(
    conn, fq: str, source_id: str, model_name: str, period: str,
    run_id: Optional[str] = None, latest_only: bool = True,
) -> List[Dict[str, Any]]:
    return fetch_model_queries(
        conn, fq, source_id, model_name,
        since_sql=since_clause("STARTED_AT", period),
        run_id=run_id,
        latest_only=latest_only,
    )


def fetch_model_compiled_sql(conn, fq: str, source_id: str, model_name: str) -> Optional[str]:
    """The current compiled SQL from the manifest.

    A fallback for the level-3 view when query capture found nothing: it is one statement per model
    from the latest manifest, identical across every run, so it answers "what does this model do"
    but not "what did this run execute". The UI labels it as such.
    """
    try:
        result = query_rows(
            conn,
            f"""
            SELECT COALESCE(NULLIF(COMPILED_SQL, ''), NULLIF(RAW_SQL, ''), 'SELECT * FROM ' || MODEL_NAME || ';') AS QUERY_SQL
            FROM {fq}.DBT_MODELS
            WHERE SOURCE_ID = %s AND UPPER(MODEL_NAME) = UPPER(%s)
            LIMIT 1
            """,
            (source_id, model_name),
        )
        rows = result["rows"]
        return rows[0].get("QUERY_SQL") if rows else f"SELECT * FROM {model_name};"
    except Exception:
        return f"SELECT * FROM {model_name};"


